/**
 * Left-to-right composition plus the dual (data-first / data-last) helper that
 * makes combinators usable both ways.
 *
 * `pipe` is pure plumbing: it never inspects or runs effects, so it preserves
 * the "effects are values" invariant by construction.
 */

export function pipe<A>(a: A): A;
export function pipe<A, B>(a: A, ab: (a: A) => B): B;
export function pipe<A, B, C>(a: A, ab: (a: A) => B, bc: (b: B) => C): C;
export function pipe<A, B, C, D>(a: A, ab: (a: A) => B, bc: (b: B) => C, cd: (c: C) => D): D;
export function pipe<A, B, C, D, E>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
): E;
export function pipe<A, B, C, D, E, F>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
): F;
export function pipe<A, B, C, D, E, F, G>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
  fg: (f: F) => G,
): G;
export function pipe<A, B, C, D, E, F, G, H>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
  fg: (f: F) => G,
  gh: (g: G) => H,
): H;
export function pipe<A, B, C, D, E, F, G, H, I>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
  fg: (f: F) => G,
  gh: (g: G) => H,
  hi: (h: H) => I,
): I;
export function pipe<A, B, C, D, E, F, G, H, I, J>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
  fg: (f: F) => G,
  gh: (g: G) => H,
  hi: (h: H) => I,
  ij: (i: I) => J,
): J;
export function pipe<A, B, C, D, E, F, G, H, I, J, K>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
  fg: (f: F) => G,
  gh: (g: G) => H,
  hi: (h: H) => I,
  ij: (i: I) => J,
  jk: (j: J) => K,
): K;
export function pipe<A, B, C, D, E, F, G, H, I, J, K, L>(
  a: A,
  ab: (a: A) => B,
  bc: (b: B) => C,
  cd: (c: C) => D,
  de: (d: D) => E,
  ef: (e: E) => F,
  fg: (f: F) => G,
  gh: (g: G) => H,
  hi: (h: H) => I,
  ij: (i: I) => J,
  jk: (j: J) => K,
  kl: (k: K) => L,
): L;
export function pipe(source: unknown, ...steps: ReadonlyArray<(input: unknown) => unknown>): unknown {
  let result = source;
  for (let index = 0; index < steps.length; index += 1) {
    result = steps[index](result);
  }
  return result;
}

/**
 * Decides whether a dual call site supplied the data-first subject.
 * `args` is the full argument list the caller passed.
 */
export type DualGuard = (args: ReadonlyArray<unknown>) => boolean;

/**
 * Builds a combinator that accepts both `f(self, ...rest)` and `f(...rest)(self)`.
 *
 * Pass the data-first arity when the argument count is unambiguous, or a guard
 * when trailing parameters are optional and counting cannot decide.
 */
export function dual<DataFirst extends (...args: any[]) => any, DataLast>(
  arityOrGuard: number | DualGuard,
  body: DataFirst,
): DataFirst & DataLast {
  const isDataFirst: DualGuard =
    typeof arityOrGuard === "number" ? (args) => args.length >= arityOrGuard : arityOrGuard;

  return function (this: unknown, ...args: any[]) {
    if (isDataFirst(args)) {
      return body.apply(this, args);
    }
    return (self: unknown) => body.apply(this, [self, ...args]);
  } as DataFirst & DataLast;
}
